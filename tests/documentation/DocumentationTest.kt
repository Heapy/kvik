package kvik.documentation

import kotlin.test.*
import kvik.core.*
import kvik.cache.NativeContentStore
import kvik.cache.NativeFiles
import kvik.compiler.jvm.*
import kvik.compiler.native.*
import kvik.execution.NativeRunDirectory
import platform.posix.usleep

class DocumentationTest {
    private val identity = Sha256.digest(byteArrayOf(1))
    private val tools = listOf("jdk", "jvm-compiler", "jvm-worker", "junit").associateWith { identity }
    private val spec = DocumentationSpec("sample", setOf("jvm"), listOf(DocumentationSourceSet("main", "jvm", LogicalPath("sources/main"), emptyList(), emptyList(), setOf("jvm"))),
        DocumentationSettings(includes = listOf(LogicalPath("Module.md"))))
    private fun await(handle: RunningAction): ActionResult {
        repeat(5000) { handle.poll()?.let { return it }; usleep(1000u) }
        error("Documentation action did not finish")
    }
    private val noHost = object : ProcessHost {
        override fun start(request: ProcessRequest): OwnedProcess = error("No process expected")
        override fun close() = Unit
    }
    private val noTools = JvmToolchainProvider { error("Compiler verification must not run") }

    @Test fun recipesBindSettingsAndRestrictInputsAndOfflineConfiguration() {
        val inputs = TreeManifest(listOf(FileEntry(LogicalPath("sources/main/Api.kt"), identity), FileEntry(LogicalPath("Module.md"), identity)))
        val action = documentationAction(spec, inputs, identity, tools)
        assertEquals(CachePolicy.LOCAL, action.cachePolicy)
        assertEquals(ActionKind.GENERATE, action.kind)
        assertNotEquals(action.key(Sha256), documentationAction(spec.copy(settings = spec.settings.copy(skipDeprecated = true)), inputs, identity, tools).key(Sha256))
        assertFails { documentationAction(spec, TreeManifest(inputs.files + FileEntry(LogicalPath("extra"), identity)), identity, tools) }
        assertFails { documentationAction(spec, TreeManifest(inputs.files.dropLast(1)), identity, tools) }
        assertFails { documentationAction(spec, inputs, identity, tools - "junit") }
        val distribution = distribution()
        val config = documentationConfiguration(spec, "/fixture", distribution)
        assertEquals(true.json(), config.values["offlineMode"])
        val set = config.values.getValue("sourceSets").arrayValue().single().objectValue()
        assertEquals(true.json(), set["noJdkLink"]); assertEquals(true.json(), set["noStdlibLink"])
        assertEquals(listOf("/fixture/input/Module.md".json()).json(), set["includes"])
        assertContains(config.canonical(), "Generated by Kvik")
    }

    @Test fun unresolvedTypesExcludeProseAndLiteralsAndDiagnosticTruncationIsUnicodeSafe() {
        assertFalse(unresolvedDocumentation("<p>ERROR CLASS: Symbol not found is a compiler message.</p>"))
        assertFalse(unresolvedDocumentation("<div class=\"symbol monospace\"><span class=\"token string\">ERROR CLASS: Symbol not found</span></div>"))
        assertTrue(unresolvedDocumentation("<div class=\"symbol monospace\"><span>fun value(): </span>ERROR CLASS: Symbol not found for Value</div>"))
        val text = "\uD83D\uDE00" + "x".repeat(2047)
        assertEquals("x".repeat(2047), documentationLogSuffix(text))
    }

    private fun distribution(): DocumentationDistribution = DocumentationDistribution(DOKKA_VERSION, TreeManifest(listOf(
        "dokka-cli-2.2.0.jar", "dokka-base-2.2.0.jar", "analysis-kotlin-symbols-2.2.0.jar", "kotlinx-html-jvm-0.8.0.jar", "freemarker-2.3.31.jar"
    ).map { FileEntry(LogicalPath(it), Sha256.digest(it.encodeToByteArray())) }))

    @Test fun workerUsesVerifiedExecutionAndRejectsInvalidOrUnresolvedSitesAfterDrain() {
        for (variant in listOf("valid", "unresolved", "missing-index", "symlink", "executable", "extra-root", "timeout", "cancelled", "failed", "corrupt-tool")) {
            val root = NativeRunDirectory("/private/tmp").path
            try {
                val content = NativeContentStore("$root/store")
                val inputs = TreeManifest(listOf(FileEntry(LogicalPath("sources/main/Api.kt"), content.put("class Api".encodeToByteArray())), FileEntry(LogicalPath("Module.md"), content.put("# Module sample".encodeToByteArray()))))
                val distribution = distribution()
                NativeFiles.ensureDirectory("$root/artifacts")
                for (file in distribution.artifacts.files) NativeFiles.writeNew("$root/artifacts/${file.path.value}",
                    if (variant == "corrupt-tool") byteArrayOf(0) else file.path.value.encodeToByteArray())
                NativeFiles.writeNew("$root/documentation.json", distribution.toJson().canonical().encodeToByteArray())
                val provider = object : JvmToolchainProvider {
                    override fun verified(identities: Map<String, Digest>): JvmToolchainLayout = error("Full compiler verification is forbidden")
                    override fun verifiedExecution(identities: Map<String, Digest>, checkpoint: () -> Unit): JvmToolchainLayout {
                        checkpoint()
                        return JvmToolchainLayout(identities, "/java", "/worker", "/bta.jar", "/stdlib.jar", "/junit.jar", "$root/artifacts", "/unused-compiler.json",
                            documentationManifest = "$root/documentation.json", documentationIdentity = distribution.identity)
                    }
                }
                var launched = false; var drained = false
                val host = object : ProcessHost {
                    override fun start(request: ProcessRequest): OwnedProcess {
                        launched = true
                        assertContains(request.arguments, "kvik.jvm.DocumentationInputs")
                        assertEquals(spec.settings.timeoutMillis, request.timeoutMillis)
                        val directory = request.workingDirectory
                        assertContentEquals("dokka-cli-2.2.0.jar".encodeToByteArray(), NativeFiles.read("$directory/tools/dokka-cli-2.2.0.jar", 1000))
                        NativeFiles.writeNew(request.stdoutFile, byteArrayOf()); NativeFiles.writeNew(request.stderrFile, byteArrayOf())
                        return object : OwnedProcess {
                            override fun poll() = when (variant) {
                                "timeout" -> ProcessResult(124, timedOut = true)
                                "cancelled" -> ProcessResult(130, cancelled = true)
                                "failed" -> ProcessResult(1)
                                else -> ProcessResult(0)
                            }
                            override fun cancel() = Unit
                            override fun close() {
                                drained = true
                                NativeFiles.ensureDirectory("$directory/output/html")
                                if (variant != "missing-index") NativeFiles.writeNew("$directory/output/html/index.html",
                                    (if (variant == "unresolved") "<div class=\"symbol monospace\">ERROR CLASS: Symbol not found for Missing</div>" else "<html><p>ERROR CLASS: Symbol not found is documented prose.</p></html>").encodeToByteArray(), variant == "executable")
                                if (variant == "symlink") platform.posix.symlink("index.html", "$directory/output/html/alias.html")
                                if (variant == "extra-root") NativeFiles.writeNew("$directory/output/extra", byteArrayOf())
                            }
                        }
                    }
                    override fun close() = Unit
                }
                val executor = DocumentationActionExecutor("run", root, host, content, provider)
                executor.start("run", "docs", documentationAction(spec, inputs, identity, tools)).use { handle ->
                    if (variant == "corrupt-tool") { assertFails { await(handle) }; assertFalse(launched) }
                    else {
                        val result = await(handle)
                        assertTrue(launched && drained)
                        assertEquals(when (variant) { "valid" -> ActionStatus.EXECUTED; "cancelled" -> ActionStatus.CANCELLED; else -> ActionStatus.FAILED }, result.status, variant)
                        assertEquals(if (variant == "valid") 1 else 0, result.outputs.files.size)
                    }
                }
            } finally { NativeFiles.removeTree(root) }
        }
    }

    @Test fun nativeStdlibCaptureIsIndependentCacheableDeclaredInput() {
        val root = NativeRunDirectory("/private/tmp").path
        try {
            val target = NativeTarget.MACOS_ARM64
            val nativeTools = target.toolIdentityNames.associateWith { identity }
            val action = documentationNativeStdlibAction(target, identity, nativeTools)
            assertEquals(CachePolicy.LOCAL, action.cachePolicy)
            assertTrue(action.inputs.files.isEmpty())
            val home = "$root/native"
            NativeFiles.ensureDirectory("$home/klib/common/stdlib/default")
            NativeFiles.writeNew("$home/klib/common/stdlib/default/manifest", "unique_name=kotlin".encodeToByteArray())
            val content = NativeContentStore("$root/store")
            var verified = false
            val provider = NativeToolchainProvider { identities ->
                assertEquals(nativeTools, identities); verified = true
                NativeToolchainLayout("$home/bin/konanc", "/jdk", "/sdk", "/dependencies", "/developer", nativeHome = home)
            }
            val executor = DocumentationActionExecutor("run", root, noHost, content, noTools, mapOf(target to provider))
            val result = executor.start("run", "stdlib", action).use(::await)
            assertTrue(verified); assertEquals(ActionStatus.EXECUTED, result.status)
            assertEquals("stdlib/default/manifest", result.outputs.files.single().path.value)
            assertContentEquals("unique_name=kotlin".encodeToByteArray(), content.get(result.outputs.files.single().digest))
        } finally { NativeFiles.removeTree(root) }
    }
}
