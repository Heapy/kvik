package kvik.documentation

import kvik.core.*
import kvik.compiler.jvm.jvmHostPlatform

fun documentationAction(spec: DocumentationSpec, inputs: TreeManifest, composition: Digest,
    toolchains: Map<String, Digest>): ActionSpec {
    require(toolchains.keys == setOf("jdk", "jvm-compiler", "jvm-worker", "junit")) { "Documentation requires the verified JVM worker identities" }
    require(inputs.files.size in 1..100_000 && inputs.files.none { it.executable } &&
        inputs.files.all { it.digest.sizeBytes <= 128L * 1024 * 1024 } &&
        inputs.files.sumOf { it.digest.sizeBytes } <= 512L * 1024 * 1024) { "Documentation inputs exceed their bounds" }
    for (source in spec.sourceSets) {
        require(inputs.files.none { it.path == source.sourceRoot }) { "Documentation source root is a file" }
        require(inputs.files.filter { it.path.value.startsWith(source.sourceRoot.value + "/") }.all { it.path.value.endsWith(".kt") }) { "Non-Kotlin documentation source" }
        for (path in source.classpath) require(inputs.files.any { it.path == path || it.path.value.startsWith(path.value + "/") }) { "Undeclared documentation classpath: ${path.value}" }
    }
    require(spec.sourceSets.any { source -> inputs.files.any { it.path.value.startsWith(source.sourceRoot.value + "/") } }) { "No documentation sources" }
    require(spec.settings.includes.all { path -> inputs.files.any { it.path == path } }) { "Undeclared documentation include" }
    require(inputs.files.all { file -> file.path in spec.settings.includes || spec.sourceSets.any { source ->
        file.path.value.startsWith(source.sourceRoot.value + "/") || source.classpath.any { file.path == it || file.path.value.startsWith(it.value + "/") }
    } }) { "Unselected documentation input" }
    return ActionSpec("kvik-dokka-html-v1", composition, ActionKind.GENERATE, jvmHostPlatform(), "common",
        toolchains.toMap(), TreeManifest(inputs.files.toList()), listOf(LogicalPath("html")), listOf("dokka", DOKKA_VERSION),
        mapOf("LANG" to "C.UTF-8", "PATH" to "/usr/bin:/bin"), spec.toJson(), spec.settings.timeoutMillis, CachePolicy.LOCAL)
}

internal fun documentationConfiguration(spec: DocumentationSpec, directory: String, distribution: DocumentationDistribution): JsonValue.Object {
    fun sourceId(name: String) = obj("scopeId" to spec.module.json(), "sourceSetName" to name.json())
    return obj("moduleName" to spec.module.json(), "outputDir" to "$directory/output/html".json(),
        "offlineMode" to true.json(), "failOnWarning" to spec.settings.failOnWarning.json(),
        "suppressInheritedMembers" to spec.settings.suppressInheritedMembers.json(),
        "pluginsConfiguration" to listOf(obj("fqPluginName" to "org.jetbrains.dokka.base.DokkaBase".json(),
            "serializationFormat" to "JSON".json(), "values" to obj("footerMessage" to "Generated by Kvik".json()).canonical().json())).json(),
        "includes" to spec.settings.includes.map { "$directory/input/${it.value}".json() }.json(),
        "pluginsClasspath" to distribution.pluginPaths.map { "$directory/tools/${it.value}".json() }.json(),
        "sourceSets" to spec.sourceSets.map { source -> obj("sourceSetID" to sourceId(source.name), "displayName" to source.name.json(),
            "dependentSourceSets" to source.dependsOn.map(::sourceId).json(), "analysisPlatform" to source.platform.json(),
            "sourceRoots" to listOf("$directory/input/${source.sourceRoot.value}".json()).json(),
            "classpath" to source.classpath.map { "$directory/input/${it.value}".json() }.json(),
            "documentedVisibilities" to spec.settings.documentedVisibilities.map { it.uppercase().json() }.json(),
            "reportUndocumented" to spec.settings.reportUndocumented.json(), "skipDeprecated" to spec.settings.skipDeprecated.json(),
            "includes" to spec.settings.includes.map { "$directory/input/${it.value}".json() }.json(),
            "noStdlibLink" to true.json(), "noJdkLink" to true.json(), "externalDocumentationLinks" to emptyList<JsonValue>().json()) }.json())
}

/** Native stdlib is captured as a declared artifact, never discovered implicitly by Dokka. */
fun documentationNativeStdlibAction(target: NativeTarget, composition: Digest, toolchains: Map<String, Digest>): ActionSpec {
    require(toolchains.keys == target.toolIdentityNames) { "Native documentation stdlib requires exact Native tool identities" }
    return ActionSpec("kvik-documentation-native-stdlib-v1", composition, ActionKind.GENERATE, target.executionPlatform,
        target.projectName, toolchains.toMap(), TreeManifest(emptyList()), listOf(LogicalPath("stdlib")), listOf("kvik.capture.native-stdlib"),
        emptyMap(), obj("target" to target.projectName.json()), 120_000, CachePolicy.LOCAL)
}
